/**
 * scripts/deploy-sponsors-worker.mjs
 * ════════════════════════════════════════════════════════
 * INSTANT SPONSOR API DEPLOY — Cloudflare Worker via API
 * Pages deploy ka wait nahi — 5-10 seconds mein live!
 * ════════════════════════════════════════════════════════
 *
 * Usage:
 *   node scripts/deploy-sponsors-worker.mjs
 *
 * Kya karta hai:
 *   1. KV se sponsor data read karta hai
 *   2. Ek standalone Cloudflare Worker deploy karta hai
 *   3. Worker /api/sponsors aur /api/sponsors2 serve karta hai
 *   4. Sirf 5-10 seconds mein live!
 */

import { readFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

// .env se credentials load karo
try {
  const env = readFileSync(join(ROOT, '.env'), 'utf8');
  for (const line of env.split('\n')) {
    const [k, ...v] = line.split('=');
    if (k && v.length) process.env[k.trim()] = v.join('=').trim();
  }
} catch {}

const ACCOUNT_ID = process.env.CLOUDFLARE_ACCOUNT_ID;
const API_TOKEN = process.env.CLOUDFLARE_API_TOKEN;
const KV_NAMESPACE_ID = 'aa59493bbbed47c0af878405e12bd8fb';
const WORKER_NAME = 'net27-sponsors-api';

if (!ACCOUNT_ID || !API_TOKEN) {
  console.error('❌ .env mein CLOUDFLARE_ACCOUNT_ID ya CLOUDFLARE_API_TOKEN nahi mila!');
  process.exit(1);
}

// Sponsors data from sponsors.js fallback (already has inline Base64)
const sponsorsJsPath = join(ROOT, 'functions', 'api', 'sponsors.js');
const sponsorsJsContent = readFileSync(sponsorsJsPath, 'utf8');

// Worker script — KV se data le ya fallback use karo
// CORS headers taake net27.watch pe kaam kare
const workerScript = `
// Auto-generated by deploy-sponsors-worker.mjs
// Deploys /api/sponsors and /api/sponsors2 as a standalone Worker

${sponsorsJsContent.replace('export async function onRequest(context)', `
// Cloudflare Worker format (not Pages Function format)
export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const path = url.pathname;

    // CORS preflight
    if (request.method === 'OPTIONS') {
      return new Response(null, {
        headers: {
          'Access-Control-Allow-Origin': '*',
          'Access-Control-Allow-Methods': 'GET, OPTIONS',
          'Access-Control-Allow-Headers': '*',
        }
      });
    }

    if (path === '/api/sponsors' || path === '/api/sponsors2' || path.startsWith('/api/sponsors')) {
      const context = { env, request };
      return onRequest(context);
    }

    return new Response('Not Found', { status: 404 });
  }
};

async function onRequest(context)`)
  .replace(/export async function onRequest\(context\)/g, 'async function onRequest(context)')}
`;

async function deployWorker() {
  console.log('\n⚡ INSTANT Sponsor API Worker Deploy');
  console.log('═'.repeat(50));
  console.log(`Worker: ${WORKER_NAME}`);
  console.log(`Account: ${ACCOUNT_ID}`);

  // Step 1: Worker create/update karo
  const url = `https://api.cloudflare.com/client/v4/accounts/${ACCOUNT_ID}/workers/scripts/${WORKER_NAME}`;

  const formData = new FormData();
  formData.append('metadata', JSON.stringify({
    main_module: 'worker.js',
    compatibility_date: '2026-06-23',
    bindings: [
      {
        type: 'kv_namespace',
        name: 'SPONSORS',
        namespace_id: KV_NAMESPACE_ID,
      }
    ]
  }), { type: 'application/json' });

  formData.append('worker.js', new Blob([workerScript], { type: 'application/javascript+module' }), 'worker.js');

  console.log('📤 Uploading Worker script...');

  const res = await fetch(url, {
    method: 'PUT',
    headers: {
      'Authorization': `Bearer ${API_TOKEN}`,
    },
    body: formData,
    signal: AbortSignal.timeout(30_000),
  });

  const data = await res.json();
  if (!data.success) {
    console.error('❌ Worker deploy failed:', JSON.stringify(data.errors, null, 2));
    process.exit(1);
  }

  console.log(`✅ Worker "${WORKER_NAME}" deployed successfully!`);
  console.log(`🌐 Worker URL: https://${WORKER_NAME}.${ACCOUNT_ID.slice(0,6)}.workers.dev`);
  console.log('\n⚠️  NOTE: Worker is on workers.dev — Pages Functions still needed for net27.watch/api/sponsors');
  console.log('═'.repeat(50));
}

deployWorker().catch(err => {
  console.error('Fatal:', err.message);
  process.exit(1);
});
